// Generates the font stylesheet and the Japanese web-font subset.
//
//   src/styles/fonts.css        Instrument Serif (display, fontsource). Inlined into every page.
//   public/fonts/noto-sans-jp.<hash>.woff2
//                               Subset built by scripts/subset-font.py from the site's own text
//                               (+ ASCII, kana, punctuation). ~0.3 MB instead of ~5 MB of pieces.
//   src/data/fonts.generated.ts URL of the subset + the @font-face rule text, used by BaseLayout at runtime.
//
// Loading policy (see DESIGN.md / docs/review/r2/R2_REPORT.md):
//   first visit  → system Japanese font; the subset is fetched at low priority after window.load
//                  and a flag is stored in localStorage.
//   later visits → BaseLayout declares the @font-face before first paint (font-display: optional),
//                  so the cached subset applies immediately with no layout shift.
//
// Fallback: if Python/fonttools are unavailable the previous fontsource pieces are used.
// Run: node scripts/build-fonts-css.mjs   (also runs automatically before `dev` / `build`)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, existsSync, copyFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const serif400 = readFileSync('node_modules/@fontsource/instrument-serif/400.css', 'utf8');
const serif400i = readFileSync('node_modules/@fontsource/instrument-serif/400-italic.css', 'utf8');
const rebase = (css, pkgPath) => css.replace(/url\(\.\/files\//g, `url(../../node_modules/${pkgPath}/files/`);

let css = `/* GENERATED by scripts/build-fonts-css.mjs — do not edit by hand. */\n\n/* Instrument Serif — display (SIL OFL 1.1) */\n`;
css += rebase(serif400 + '\n' + serif400i, '@fontsource/instrument-serif');

mkdirSync('public/fonts', { recursive: true });
const tmp = 'public/fonts/_subset.tmp.woff2';
let mode = 'subset';
const py = spawnSync('python', ['scripts/subset-font.py', tmp], { encoding: 'utf8' });
if (py.status !== 0 || !existsSync(tmp)) {
  mode = 'fallback';
  console.warn('[fonts] subset failed (' + (py.stderr || py.error?.message || '').trim().split('\n').pop() + '). Falling back to fontsource pieces.');
}

let subsetUrl = null;
let notoFontFace = null;
if (mode === 'subset') {
  const buf = readFileSync(tmp);
  const hash = createHash('md5').update(buf).digest('hex').slice(0, 8);
  const name = `noto-sans-jp.${hash}.woff2`;
  for (const f of readdirSync('public/fonts')) if (/^noto-sans-jp\.[0-9a-f]{8}\.woff2$/.test(f) && f !== name) unlinkSync(`public/fonts/${f}`);
  copyFileSync(tmp, `public/fonts/${name}`);
  unlinkSync(tmp);
  subsetUrl = `/fonts/${name}`;
  // The @font-face is NOT placed in the page CSS: a rule present at first render makes Chrome request the
  // font at VeryHigh priority immediately (even with font-display: optional), which competes with the hero
  // image on slow networks. BaseLayout injects the rule before first paint only when the browser has already
  // fetched the file once (flag in localStorage); otherwise it fetches the file at low priority after window.load.
  notoFontFace = `@font-face{font-family:'Noto Sans JP Variable';font-style:normal;font-display:optional;font-weight:100 900;src:url(${subsetUrl}) format('woff2-variations'),url(${subsetUrl}) format('woff2')}`;
  css += `\n\n/* Noto Sans JP Variable — body (SIL OFL 1.1): site subset ${subsetUrl} (${(buf.length / 1024).toFixed(0)} KB), declared at runtime by BaseLayout */\n`;
  console.log(`[fonts] ${py.stdout.trim()} → ${subsetUrl}`);
} else {
  const notoDir = 'node_modules/@fontsource-variable/noto-sans-jp';
  mkdirSync('public/fonts/noto', { recursive: true });
  for (const f of readdirSync(`${notoDir}/files`)) if (f.endsWith('.woff2') && f.includes('wght-normal')) copyFileSync(`${notoDir}/files/${f}`, `public/fonts/noto/${f}`);
  css += `\n\n/* Noto Sans JP Variable — fontsource pieces (fallback build) */\n` + readFileSync(`${notoDir}/index.css`, 'utf8').replace(/url\(\.\/files\//g, 'url(/fonts/noto/').replace(/font-display: swap;/g, 'font-display: optional;');
}

writeFileSync('src/styles/fonts.css', css);
writeFileSync('src/data/fonts.generated.ts', `// GENERATED by scripts/build-fonts-css.mjs\nexport const notoSubsetUrl: string | null = ${JSON.stringify(subsetUrl)};\nexport const notoFontFace: string | null = ${JSON.stringify(notoFontFace)};\n`);
if (existsSync('public/fonts/noto-sans-jp.css')) unlinkSync('public/fonts/noto-sans-jp.css');
console.log(`[fonts] mode=${mode}; src/styles/fonts.css written`);
